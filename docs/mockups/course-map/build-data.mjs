// Builds data.js for the Course Map mockups from the live content, so the
// mockups open over file:// with real titles and real asset paths.
// Run: node docs/mockups/course-map/build-data.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, "../../..");
const read = path => JSON.parse(readFileSync(join(root, path), "utf8"));

const index = read("content/unit-index.json");
const presentation = read("content/presentation.json");
const reference = read("content/reference.json");
const fieldNotes = read("content/field-notes.json");
const mastery = read("content/mastery-index.json");

// Same five values as src/styles/board.css `.world.theme-*`.
const palettes = {
  moonroot: { dark: "#071d18", mid: "#1c533d", bright: "#77e0a3", magic: "#a77bff", warm: "#ffc866" },
  ember: { dark: "#20120e", mid: "#683420", bright: "#f59a61", magic: "#ff7468", warm: "#ffd06c" },
  glass: { dark: "#0b1722", mid: "#234f68", bright: "#78dbea", magic: "#b89cff", warm: "#ffe08b" },
  deepwater: { dark: "#07151d", mid: "#123f4e", bright: "#55bfd0", magic: "#888cff", warm: "#f6bd63" }
};

const units = index.units
  .slice()
  .sort((a, b) => a.unitNumber - b.unitNumber)
  .map(entry => {
    const unit = read(join("content", entry.path.replace(/^(\.\.\/)*content\//, "")));
    const view = presentation.units[entry.id];
    const world = presentation.worlds[view.worldId];
    const scene = view.scenes[view.sceneId];
    return {
      id: entry.id,
      number: entry.unitNumber,
      title: entry.title,
      surface: entry.surface || null,
      editorNote: entry.editorNote || null,
      prerequisites: entry.prerequisiteSkillIds || [],
      recommended: entry.recommendedSkillIds || [],
      worldId: view.worldId,
      palette: palettes[world.autoThemeId],
      gradient: world.fallbackGradient,
      guide: view.guideCharacterId,
      board: scene.profiles.compact.base,
      wideBoard: scene.profiles.wide.base,
      painting: view.completion.storyImage,
      completion: view.completion.copy,
      hook: view.completion.nextHook?.copy || null,
      commandCount: (unit.reference || []).length,
      lessons: unit.lessons.map(lesson => ({
        id: lesson.id,
        title: lesson.title,
        track: lesson.track || "core",
        activities: (lesson.activities || []).map(activity => ({
          id: activity.id,
          title: activity.title,
          type: activity.type
        }))
      }))
    };
  });

const data = {
  arcs: index.arcs
    .slice()
    .sort((a, b) => a.arcNumber - b.arcNumber)
    .map(arc => ({ id: arc.id, number: arc.arcNumber, title: arc.title, unitNumbers: arc.unitNumbers })),
  units,
  worlds: Object.values(presentation.worlds).map(world => ({
    id: world.id,
    name: world.displayName,
    palette: palettes[world.autoThemeId]
  })),
  story: {
    intro: presentation.story.intro.map(panel => ({ id: panel.id, asset: panel.asset, copy: panel.copy })),
    ending: { title: presentation.story.ending.title, image: presentation.story.ending.asset }
  },
  decks: reference.decks.map(deck => ({
    id: deck.id,
    kicker: deck.kicker,
    title: deck.title,
    summary: deck.summary,
    cards: deck.cards.map(card => card.title)
  })),
  fieldNotes: fieldNotes.notes.map(note => ({ id: note.id, title: note.title, kicker: note.kicker, summary: note.summary })),
  concepts: mastery.units.flatMap(unit =>
    (unit.coverage || []).map(item => ({ id: item.id, unitId: unit.id, unitNumber: unit.unitNumber, concept: item.concept }))
  )
};

writeFileSync(join(here, "data.js"), `// Generated by build-data.mjs from content/. Do not edit.\nwindow.MAP_DATA = ${JSON.stringify(data, null, 1)};\n`);
console.log(`data.js: ${units.length} units, ${data.concepts.length} concepts, ${data.decks.length} decks`);
